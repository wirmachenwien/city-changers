// Export the selected geometry as nine-slice CSS masks. No artwork or mascot rendering.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { bubblePath, compactPath, framePath } from './geometry.js';

const profiles = {
  frame: { path: framePath(320, 180), box: [0, 0, 320, 180], cuts: [16, 16, 16, 16], weight: 1.5 },
  compact: { path: compactPath(144, 44), box: [0, 0, 144, 44], cuts: [10, 10, 10, 10], weight: 2 },
  'bubble-side': { path: bubblePath(320, 180, false), box: [-24, 0, 344, 180], cuts: [88, 24, 24, 104], weight: 2 },
  'bubble-top': { path: bubblePath(320, 180, true), box: [0, -24, 320, 204], cuts: [112, 24, 24, 88], weight: 2 },
};

export function cssFrameFiles() {
  const files = new Map();
  let css = '/* Generated by build-css-frames.mjs; edit geometry.js, not these exports. */\n:root {\n';
  for (const [name, { path, box, cuts, weight }] of Object.entries(profiles)) {
    const [x, y, width, height] = box;
    const [top, right, bottom, left] = cuts;
    const columns = [[x, left], [x + left, width - left - right], [x + width - right, right]];
    const rows = [[y, top], [y + top, height - top - bottom], [y + height - bottom, bottom]];
    const names = ['nw', 'n', 'ne', 'w', 'c', 'e', 'sw', 's', 'se'];
    const views = rows.flatMap(([vy, h], row) => columns.map(([vx, w], col) =>
      `  <view id="${names[row * 3 + col]}" viewBox="${vx} ${vy} ${w} ${h}" preserveAspectRatio="none"/>`,
    )).join('\n');
    for (const paint of ['fill', 'stroke']) {
      const file = `${name}-${paint}.svg`;
      files.set(file, `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${box.join(' ')}" preserveAspectRatio="none">\n${views}\n  <path d="${path}" fill="${paint === 'fill' ? 'currentColor' : 'none'}" stroke="${paint === 'stroke' ? 'currentColor' : 'none'}" stroke-width="${weight}" stroke-linecap="round" stroke-linejoin="round"/>\n</svg>\n`);
      // Inline each crop so first-paint decoration does not wait for an SVG
      // request or rely on SVG fragment-view support in CSS masks.
      const masks = rows.flatMap(([vy, h]) => columns.map(([vx, w]) => {
        const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${vx} ${vy} ${w} ${h}" preserveAspectRatio="none"><path d="${path}" fill="${paint === 'fill' ? 'white' : 'none'}" stroke="${paint === 'stroke' ? 'white' : 'none'}" stroke-width="${weight}" stroke-linecap="round" stroke-linejoin="round"/></svg>`;
        return `url("data:image/svg+xml,${encodeURIComponent(svg)}")`;
      }));
      css += `  --${name}-${paint}-mask: ${masks.join(', ')};\n`;
    }
    const middleWidth = `calc(100% - ${left + right}px)`;
    const middleHeight = `calc(100% - ${top + bottom}px)`;
    css += `  --${name}-mask-size: ${left}px ${top}px, ${middleWidth} ${top}px, ${right}px ${top}px, ${left}px ${middleHeight}, ${middleWidth} ${middleHeight}, ${right}px ${middleHeight}, ${left}px ${bottom}px, ${middleWidth} ${bottom}px, ${right}px ${bottom}px;\n`;
  }
  files.set('frames.css', css + '}\n');
  return files;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const directory = new URL('./frames/', import.meta.url);
  const check = process.argv.includes('--check');
  if (!check) mkdirSync(directory, { recursive: true });
  for (const [name, content] of cssFrameFiles()) {
    const file = new URL(name, directory);
    if (check) {
      if (readFileSync(file, 'utf8') !== content) throw new Error(`Stale CSS frame: ${name}`);
    } else writeFileSync(file, content);
  }
}

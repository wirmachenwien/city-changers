#!/usr/bin/env node
// Approved SVG sources live in drawn/. Old is reference-only. No motion.
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';
import { spawnSync } from 'node:child_process';

const root = fileURLToPath(new URL('../../', import.meta.url));
const design = join(root, 'design/icons');
const check = process.argv.includes('--check');
const manifest = JSON.parse(readFileSync(join(design, 'manifest.json'), 'utf8'));
const palette = JSON.parse(readFileSync(join(root, 'src/data/colors.generated.json'), 'utf8'));
const sha = value => createHash('sha256').update(value).digest('hex');
if (palette.registrySha256 !== sha(readFileSync(join(root, 'design/colors.json')))) {
  throw new Error('Generated colors are outdated; run npm run colors:generate first.');
}
const files = readdirSync(join(design, 'drawn')).filter(name => name.endsWith('.svg')).sort();
const expected = manifest.icons.map(icon => `${icon.id}.svg`).sort();
if (JSON.stringify(files) !== JSON.stringify(expected)) throw new Error('Icon manifest/source mismatch');
const outputs = new Map();
const runtime = {};
const catalog = manifest.icons.map(icon => {
  const selected = readFileSync(join(design, 'drawn', `${icon.id}.svg`), 'utf8').trim();
  if (!selected.includes('viewBox="0 0 24 24"')) throw new Error(`Invalid icon grid: ${icon.id}`);
  runtime[icon.id] = selected.replace('<svg ', '<svg class="icon" aria-hidden="true" focusable="false" ');
  outputs.set(`src/assets/icons/${icon.id}.svg`, selected + '\n');
  return { ...icon, brand: !!icon.brand, svg: selected, note: icon.id === 'link' ?
    'Redrawn as two open, joined chain loops with a distinct connecting bridge.' :
    ['spark', 'spark-outline'].includes(icon.id) ? 'Used on lists at generous 1.1rem size.' :
    icon.accent ? 'Decorative icon with a matching solid or outline variant.' :
    icon.brand ? 'Selected hand-drawn frame; the recognizable social silhouette is preserved.' :
    'Hand-drawn family selected and applied to the production interface.' };
});
outputs.set('src/data/icons.generated.json', JSON.stringify(runtime, null, 2) + '\n');
const artwork = [
  ['favicon.svg', 'public/favicon.svg'], ['favicon.png', 'public/favicon.png'], ['favicon.ico', 'public/favicon.ico'],
  ['apple-touch-icon.png', 'public/apple-touch-icon.png'], ['icon-192.png', 'public/icon-192.png'],
  ['icon-512.png', 'public/icon-512.png'], ['logo-small.svg', 'src/assets/site/logo-small.svg'],
  ['cc-by.svg', 'src/assets/site/cc-by.svg'], ['cc-by-88x31.png', 'src/assets/site/cc-by-88x31.png'],
];
for (const [name, source] of artwork) outputs.set(`design/icons/artwork/${name}`, readFileSync(join(root, source)));
outputs.set('design/icons/catalog.js', `// Generated by design/icons/build-icons.mjs. Edit drawn/*.svg, not production outputs.\nwindow.iconCatalog = ${JSON.stringify(catalog, null, 2)};\nwindow.iconArtwork = ${JSON.stringify(artwork)};\n`);
const colors = Object.fromEntries(['light', 'dark'].map(theme => [theme, {
  ink: palette.themes[theme].ink, accent: palette.themes[theme].accent,
}]));
const fingerprint = sha(JSON.stringify({ sources: runtime, colors, size: manifest.pngSize,
  roles: Object.fromEntries(manifest.icons.map(icon => [icon.id, icon.accent ? 'accent' : 'ink'])),
  renderer: readFileSync(join(design, 'render-pngs.py'), 'utf8') }));
const statePath = join(design, 'build-state.json');
const state = existsSync(statePath) ? JSON.parse(readFileSync(statePath, 'utf8')) : {};
const pngPaths = manifest.icons.flatMap(icon => ['light', 'dark'].map(theme => `src/assets/icons/png/${theme}/${icon.id}.png`));
const pngFresh = state.inputs === fingerprint && pngPaths.every(path =>
  existsSync(join(root, path)) && state.pngs?.[path] === sha(readFileSync(join(root, path))));
let stale = false;
for (const [path, content] of outputs) {
  const target = join(root, path);
  const data = Buffer.isBuffer(content) ? content : Buffer.from(content);
  if (check) {
    if (!existsSync(target) || !readFileSync(target).equals(data)) { console.error(`Stale icon output: ${path}`); stale = true; }
  } else {
    mkdirSync(join(target, '..'), { recursive: true });
    if (!existsSync(target) || !readFileSync(target).equals(data)) writeFileSync(target, data);
  }
}
if (check && !pngFresh) { console.error('Stale icon PNGs; run npm run icons:build'); stale = true; }
if (!check && !pngFresh) {
  const result = spawnSync('python3', [join(design, 'render-pngs.py')], { cwd: root, stdio: 'inherit' });
  if (result.status !== 0) process.exit(result.status ?? 1);
  const pngs = Object.fromEntries(pngPaths.map(path => [path, sha(readFileSync(join(root, path)))]));
  writeFileSync(statePath, JSON.stringify({ inputs: fingerprint, pngs }, null, 2) + '\n');
}
if (stale) process.exitCode = 1;
else console.log(`${check ? 'Checked' : 'Built'} ${manifest.icons.length} SVGs + ${pngPaths.length} light/dark PNGs; source drawings and old archive preserved.`);
